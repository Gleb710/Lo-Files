library;

/// Статус синхронизации записи Recent/Favorite с backend-модулем Sync.
///
/// ВАЖНО (задел на будущее, не использовать в MVP):
/// Поле привязано к зарезервированному столбцу `sync_status` в Drift-таблицах
/// `recent_entries` и `favorites` (см. docs/architecture.md, раздел 9.1).
/// Backend-модуль Sync в MVP НЕ реализуется (docs/architecture.md, раздел 2.3,
/// таблица "Модули backend'а" — статус "Не реализуется"), поэтому в MVP
/// значение этого поля всегда `null` и физически не может быть достоверным.
///
/// Поле введено в модель уже сейчас (а не при появлении модуля синхронизации),
/// чтобы не пришлось менять сигнатуру `RecentEntry`/`FavoriteEntry` после того,
/// как на неё уже будет ссылаться код use case'ов, репозиториев и UI.
///
/// НЕ ИСПОЛЬЗОВАТЬ в бизнес-логике MVP: ни один use case, репозиторий или
/// экран не должен принимать решения на основе значения `SyncStatus`, пока
/// модуль синхронизации фактически не реализован.
enum SyncStatus {
  /// Запись создана локально и ещё не отправлялась на сервер.
  pending,

  /// Запись успешно синхронизирована с сервером.
  synced,

  /// Последняя попытка синхронизации завершилась ошибкой.
  failed,
}