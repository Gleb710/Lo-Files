// lib/features/storage/domain/repositories/folder_repository.dart

import '../../../../core/result/result.dart';
import '../models/folder.dart';

/// Контракт репозитория для работы с папками виртуального хранилища.
///
/// [FolderRepository] — это интерфейс уровня Domain-слоя, который объявляет
/// операции CRUD для папок, но не содержит никакой реализации, связанной
/// с конкретной БД (Drift), сетью или файловой системой устройства.
/// Реализация появится в Data-слое на неделе 3 как `DriftFolderRepository`,
/// работающая с локальной SQLite-таблицей `folders`.
///
/// ## Точка расширения для облачных хранилищ
/// Этот интерфейс спроектирован так, чтобы в будущем облачное хранилище
/// (Google Drive, OneDrive) могло стать альтернативной реализацией того
/// же интерфейса без изменения кода, который его использует (см.
/// docs/architecture.md, раздел 10 — Repository Interface). Presentation-
/// слой и use case'ы зависят только от этого контракта, а не от конкретной
/// реализации.
///
/// ## Обработка ошибок
/// Все методы возвращают `Result<T>` (docs/architecture.md, раздел 3.4 —
/// Result / Envelope Pattern, пункт А). Это означает, что вызывающий код
/// обязан явно обработать оба исхода: успех (`Result.success`) или ошибку
/// (`Result.failure` с `errorCode` и `errorMessage`). Исключения не
/// выбрасываются на границах слоёв use case — любые ошибки Drift, сети
/// или файловой системы должны быть перехвачены в Data-слое и завёрнуты
/// в `Result.failure` с соответствующим кодом ошибки.
///
/// ## Рекурсивное удаление папок
/// Метод [deleteFolder] поддерживает параметр [recursive]. Если
/// [recursive] равен `true`, папка удаляется вместе со всеми вложенными
/// файлами и подпапками. Если `false` — удаление папки с вложениями
/// должно завершиться ошибкой (например, 'folder_not_empty'), чтобы
/// Presentation-слой мог показать пользователю предупреждение перед
/// удалением (соответствие UX-требованию из PRD).
///
/// ## Типы идентификаторов
/// - `folderId` — `String` (не `int`), так как в будущем может потребоваться
///   использовать UUID или аналог для кросс-платформенной совместимости
///   с облачными API.
/// - `parentId` в [createFolder] и `targetParentId` в [moveFolder] могут
///   быть `null`, что означает корень виртуального хранилища (аналог
///   `Folder.parentId == null` в доменной модели).
abstract class FolderRepository {
  /// Возвращает список папок с указанным родителем.
  ///
  /// Если [parentId] равен `null`, возвращает папки корневой папки
  /// виртуального хранилища (аналог `Folder.parentId == null`).
  ///
  /// Возвращает `Result.success` со списком папок (пустой список, если
  /// родитель не содержит подпапок) или `Result.failure` с кодом ошибки
  /// (например, 'folder_not_found', если [parentId] указан, но не существует).
  Future<Result<List<Folder>>> getFolders(String? parentId);

  /// Создаёт новую папку в хранилище.
  ///
  /// [folder] — доменная модель папки, которая должна быть сохранена.
  /// [folder.parentId] может быть `null`, что означает создание в корне
  /// виртуального хранилища.
  ///
  /// В Data-слое [folder] будет преобразован в storage-модель `Folders`
  /// через отдельный маппер (см. docs/architecture.md, раздел 3.7 —
  /// Domain Model vs Storage Model vs DTO vs View Model).
  ///
  /// Возвращает `Result.success` с сохранённой доменной моделью (возможно,
  /// с обновлёнными полями, такими как сгенерированный `id` или
  /// `createdAt`) или `Result.failure` с кодом ошибки (например,
  /// 'duplicate_name', если папка с таким именем уже существует у того
  /// же родителя, или 'folder_not_found', если [folder.parentId] указан,
  /// но не существует).
  Future<Result<Folder>> createFolder(Folder folder);

  /// Переименовывает папку с указанным [folderId].
  ///
  /// [newName] — новое имя папки (без пути, только базовое имя).
  ///
  /// Возвращает `Result.success` с обновлённой доменной моделью или
  /// `Result.failure` с кодом ошибки (например, 'folder_not_found', если
  /// [folderId] не существует, или 'duplicate_name', если новое имя уже
  /// занято у того же родителя).
  Future<Result<Folder>> renameFolder(String folderId, String newName);

  /// Перемещает папку с указанным [folderId] под другого родителя.
  ///
  /// [targetParentId] — идентификатор нового родителя. Если `null`, означает
  /// перемещение в корень виртуального хранилища (аналог
  /// `Folder.parentId == null`).
  ///
  /// Возвращает `Result.success` с обновлённой доменной моделью или
  /// `Result.failure` с кодом ошибки (например, 'folder_not_found', если
  /// [folderId] или [targetParentId] не существуют, или
  /// 'circular_reference', если попытаться переместить папку в её же
  /// потомка, создав цикл в иерархии).
  Future<Result<Folder>> moveFolder(String folderId, String? targetParentId);

  /// Удаляет папку с указанным [folderId] из хранилища.
  ///
  /// Если [recursive] равен `true`, папка удаляется вместе со всеми
  /// вложенными файлами и подпапками. Если `false` — попытка удалить
  /// папку с вложениями должна завершиться ошибкой 'folder_not_empty',
  /// чтобы Presentation-слой мог показать пользователю предупреждение.
  ///
  /// Возвращает `Result.success` с удалённой доменной моделью (если нужно
  /// для отката операции) или `Result.failure` с кодом ошибки (например,
  /// 'folder_not_found', если [folderId] не существует, или
  /// 'folder_not_empty', если [recursive] == false и папка не пуста).
  Future<Result<Folder>> deleteFolder(String folderId, {bool recursive});
}