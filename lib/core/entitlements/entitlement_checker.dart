// lib/core/entitlements/entitlement_checker.dart

/// Контракт проверки доступности функций, защищённых лицензией/подпиской.
///
/// [EntitlementChecker] вызывается из точек расширения ядра — Viewer
/// Registry и File Action Registry — непосредственно перед тем, как
/// показать пользователю функциональность, предоставляемую плагином
/// (например, платный редактор PDF или архиватор). Это интерфейс уровня
/// Core: реестры зависят только от него, а не от конкретной реализации
/// (см. docs/architecture.md, раздел 3.6 — Strategy Pattern через
/// EntitlementChecker, и раздел 3.5 — DI через Riverpod).
///
/// ## Статус в MVP
/// В MVP используется единственная реализация — `StubEntitlementChecker`,
/// которая всегда возвращает `false` (см. docs/architecture.md, раздел
/// 3.6: «в MVP единственная реализация всегда возвращает false — плагинов
/// физически нет»). Настоящих плагинов и покупок в MVP не существует,
/// поэтому проверка синхронна и не обращается к сети.
///
/// ## Что изменится после MVP (известное ограничение)
/// После MVP появится реальная реализация, обращающаяся к backend'у:
/// backend будет уведомляться об изменении подписки через webhook от
/// RevenueCat, а `EntitlementChecker` начнёт кэшировать ответ backend'а
/// на короткое время, чтобы не делать сетевой запрос на каждый вызов.
/// Это означает, что сигнатуру метода почти наверняка придётся расширить
/// до асинхронной (`Future<bool>`), так как реальная проверка требует
/// сетевого обращения — сейчас синхронная сигнатура — осознанное временное
/// решение специально для MVP, а не постоянный контракт.
/// Код, который вызывает [isFeatureAvailable] сейчас (реестры), при такой
/// замене трогать нельзя — замена реализации должна происходить только
/// через подмену Riverpod-провайдера (`entitlementCheckerProvider`), а не
/// через изменение вызывающего кода.
///
/// ## Формат [featureId]
/// [featureId] — строка-константа в формате `'plugin.<имя>'`, единая для
/// Viewer Registry и File Action Registry при регистрации платных функций
/// плагинов. Примеры: `'plugin.pdf_editor'`, `'plugin.archiver'`.
/// Закрытый `enum` здесь осознанно не используется: набор фич определяется
/// плагинами, устанавливаемыми независимо от ядра приложения, поэтому
/// фиксированный список значений на уровне ядра противоречил бы самой идее
/// расширяемости (docs/architecture.md, раздел 3.1 — Registry Pattern).
abstract class EntitlementChecker {
  /// Проверяет, доступна ли пользователю функция с идентификатором
  /// [featureId].
  ///
  /// Вызывается из Viewer Registry перед показом виджета-просмотрщика
  /// плагина и из File Action Registry перед показом действия плагина
  /// в контекстном меню файла — в обоих случаях до того, как
  /// соответствующий UI-элемент становится видимым пользователю.
  ///
  /// В MVP синхронный и не выполняет сетевых обращений — см.
  /// «Что изменится после MVP» в doc-комментарии класса.
  bool isFeatureAvailable(String featureId);
}