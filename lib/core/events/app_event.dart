/// Базовый тип для всех доменных событий приложения.
///
/// Использование sealed class гарантирует, что набор наследников
/// известен компилятору внутри библиотеки. Это позволяет в будущем
/// применять exhaustive switch при обработке событий и получать
/// подсказку компилятора, если новый тип события не был обработан.
///
/// Базовый класс не содержит логики обработки событий и служит только
/// типизированной основой для конкретных событий приложения.
/// ВАЖНО для будущих событий: любой конкретный наследник AppEvent должен
/// быть частью этой же библиотеки — то есть объявляться в отдельном файле
/// с директивой `part of 'app_event.dart';`, а не через обычный `import`.
/// Иначе компилятор не признает класс подтипом sealed-иерархии.
sealed class AppEvent {
  const AppEvent({required this.occurredAt});

  /// Момент возникновения события внутри приложения.
  final DateTime occurredAt;
}
