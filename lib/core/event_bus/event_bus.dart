// lib/core/event_bus/event_bus.dart

import '../events/app_event.dart';

/// Контракт событийной шины ядра приложения.
///
/// [EventBus] позволяет модулям объявлять о произошедшем действии
/// (через [publish]) без знания о том, кто на это событие подписан, и
/// подписываться на события конкретного типа (через [on]) без знания о
/// том, кто их публикует. Это разрывает прямые зависимости между
/// модулями (см. docs/architecture.md, раздел 3.2 — Event-Driven /
/// Event Bus).
///
/// Пример: модуль Viewer публикует `FileOpened` при открытии файла,
/// а модуль Recent & Favorites и будущий модуль синхронизации
/// подписываются на `FileOpened` независимо друг от друга и друг о друге
/// не знают.
///
/// ## Синхронность
/// Шина асинхронная: [publish] добавляет событие в broadcast-поток, а
/// подписчики через [on] получают его через `Stream`-подписку, то есть
/// не в тот же микротакт, в котором был вызван [publish]. Это осознанное
/// решение для MVP: синхронная доставка потребовала бы прямого вызова
/// каждого подписчика внутри [publish], что вернуло бы шину к модели
/// прямых вызовов и свело бы на нет саму цель развязки модулей.
/// Порядок обработки одного события несколькими подписчиками относительно
/// друг друга не гарантирован — гарантирован только порядок доставки
/// разных событий одним и тем же потоком.
///
/// ## Жизненный цикл
/// [EventBus] — singleton уровня приложения (см. `eventBusProvider`,
/// `@Riverpod(keepAlive: true)`), а не state конкретного экрана.
abstract class EventBus {
  /// Публикует [event] в шину. Не блокирует вызывающий код и не ждёт,
  /// пока все подписчики обработают событие.
  void publish(AppEvent event);

  /// Возвращает поток событий, отфильтрованный по типу [T].
  ///
  /// [T] должен быть подтипом [AppEvent]. Подписчик получает только
  /// события нужного ему типа, а не все события подряд.
  Stream<T> on<T extends AppEvent>();
}
